    <p>Under Section 122 & 123 of the Transfer of Property Act, a Gift Deed must satisfy four essential statutory conditions to establish legal validity:</p>
    <ol class="step-list">
        <li><strong>Voluntary Execution Without Coercion:</strong> The donor must execute the gift deed out of free will, without any undue influence, fraud, or misrepresentation.</li>
        <li><strong>Transfer of Existing Property:</strong> The subject matter of the gift must be an existing, identifiable property. A gift of future property is legally void.</li>
        <li><strong>Absence of Consideration:</strong> The transfer must be executed entirely without cash or property consideration.</li>
        <li><strong>Acceptance by Donee:</strong> The donee must accept the gift during the donor\'s lifetime. Express acceptance is recorded on the gift deed instrument itself.</li>
    </ol>

