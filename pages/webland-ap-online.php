<h2 id="heading-3">Integration Between Webland AP and IGRS Registration System</h2>
<p class="content-text">
    A landmark reform in Andhra Pradesh’s land administration is the auto-integration between the <strong>webland ap online</strong> database and the Sub-Registrar Office (SRO) registration portal (`registration.ap.gov.in`). When a buyer and seller initiate a sale deed execution for agricultural land at an SRO in AP, the registration software performs an automated online check against Webland AP servers.
</p>
<p class="content-text">
    The automated integration verifies three mandatory legal conditions:
    1. <strong>Pattadar Title Match:</strong> Confirms that the seller’s name on the deed matches the registered Pattadar in Webland 1B ROR.
    2. <strong>Extent Availability:</strong> Confirms that the land area being sold does not exceed the unencumbered extent registered under the seller’s Khata number.
    3. <strong>Section 22A Prohibitions:</strong> Ensures the survey number is not listed as government land, assigned land, endowment property, or under court stay orders.
</p>

<h2 id="heading-4">Step-by-Step Land Title Mutation Process on Webland AP</h2>
<p class="content-text">
    After executing a sale deed or receiving inherited property in Andhra Pradesh, the new owner must apply for land title mutation to update the Webland AP 1B ROR and secure a digital Pattadar Passbook:
</p>
<ol class="step-list" style="margin-left: 1.5rem; line-height: 1.8; color: var(--text-main);">
    <li><strong>Application Submission:</strong> Submit a mutation application online via Meeseva centers or the AP Revenue portal, attaching registered sale deed copies, prior passbooks, and Aadhaar ID.</li>
    <li><strong>VRO & RI Field Inspection:</strong> The Village Revenue Officer (VRO) and Revenue Inspector (RI) conduct physical field verification to inspect plot boundaries and survey stones.</li>
    <li><strong>Public Notice Period:</strong> A 15-day public notice is issued to invite any title objections from neighbors or legal co-heirs.</li>
    <li><strong>Tahsildar Digital Order:</strong> Upon approval, the Tahsildar digitally signs the Webland mutation order, updating the <strong>meebhoomi ap adangal</strong> and 1B ROR records.</li>
    <li><strong>Passbook Generation:</strong> A fresh e-Pattadar Passbook with a unique QR code is dispatched to the landowner.</li>
</ol>

<h2 id="heading-5">Checking Section 22A Prohibited Property Listings</h2>
<p class="content-text">
    Under Section 22A of the Registration Act of 1908, specified categories of lands in Andhra Pradesh are strictly barred from private registration and sale. These prohibited categories are flagged within the <strong>webland ap gov in</strong> database:
</p>
<ul style="margin-left: 1.5rem; line-height: 1.8; margin-bottom: 1.5rem;">
    <li><strong>22A(1)(a):</strong> State government lands, ceiling surplus lands, and communal forest lands.</li>
    <li><strong>22A(1)(b):</strong> Lands belonging to Endowments (temples) and Wakf Board properties.</li>
    <li><strong>22A(1)(c):</strong> Assigned agricultural lands granted by government to landless poor families (protected under AP Assigned Lands POT Act 1977).</li>
    <li><strong>22A(1)(d):</strong> Properties attached by civil courts, enforcement agencies, or under active judicial stay orders.</li>
</ul>
<p class="content-text">
    Buyers should perform a preliminary prohibited property search on the IGRS AP portal and verify Webland AP 1B entries prior to paying token advance amounts.
</p>

<h2 id="heading-6">Resolving Survey Number & Subdivision Discrepancies</h2>
<p class="content-text">
    Discrepancies in survey numbers or subdivision extents between paper deeds and Webland digital files can stall registrations. If a survey subdivision (e.g., Survey 142/2A) displays incorrect land area on Meebhoomi, landowners must apply for a survey correction through the Webland FMB re-survey service.
</p>
<p class="content-text">
    A government Mandal Surveyor inspects the site with GPS tools, measures ground boundaries, and reconciles the Field Measurement Book (FMB) sketch. Once approved by the Assistant Director of Survey and Land Records, the updated coordinates are synced to Webland AP servers.
