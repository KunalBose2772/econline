<h2 id="heading-4">Special Marriage Act 1954 Procedure for Inter-Faith Marriages</h2>
<p class="content-text">
    Under the <strong>special marriage act tamil nadu</strong> guidelines, couples of different religions or those choosing a secular civil marriage must follow a distinct legal process:
</p>
<ul style="margin-left: 1.5rem; line-height: 1.8; margin-bottom: 1.5rem;">
    <li><strong>Notice of Intended Marriage:</strong> Submit Form 1 Notice of Intended Marriage on TNREGINET to the SRO in whose jurisdiction at least one partner has resided for at least 30 days.</li>
    <li><strong>30-Day Public Notice Display:</strong> The SRO publishes the notice on the office notice board for 30 calendar days to invite any legal objections.</li>
    <li><strong>Objection Resolution:</strong> If no valid legal objections are filed under Section 4 of the Act, solemnization is approved.</li>
    <li><strong>Declaration & Certificate:</strong> The couple and 3 witnesses sign the marriage declaration register in the presence of the Sub-Registrar to receive the Marriage Certificate.</li>
</ul>

