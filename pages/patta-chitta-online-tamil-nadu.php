<h2 id="heading-1">What is Patta and how is it different from EC?</h2>
<p class="content-text">
    A Patta (also written as Pattta or Pata) is a revenue record issued by the Tahsildar office of the respective taluk. It is the primary document that proves land ownership for revenue purposes. The Patta contains the owner name, the survey number, the land extent, the land type (wet or dry), and the property tax liability. When a property is sold, the buyer must apply for Patta transfer (Patta mutation) at the Tahsildar office to update the record in the new owner name.
</p>
<p class="content-text">
    An Encumbrance Certificate (EC), on the other hand, is issued by the registration department (SRO) and records all registered deeds executed on the property. While the Patta shows who currently owns the land according to revenue records, the EC shows the registered transaction history. A seller whose name appears on the Patta but has an undisclosed registered mortgage in the EC is a warning sign. Buyers must verify both records. For statewide EC guidance, use the <strong><a href="/ec-online/" title="Read our comprehensive guide on ec online">ec online</a></strong> resource library.
</p>

